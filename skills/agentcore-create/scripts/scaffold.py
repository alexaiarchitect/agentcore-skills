#!/usr/bin/env python3
"""Scaffold an AgentCore Runtime, Gateway, Identity or Memory resource as IaC.

Terraform is the default and the recommended path: a small module (main.tf,
variables.tf, outputs.tf, versions.tf) under infrastructure/modules/ (or
terraform/modules/ when that tree does not exist), wired from your root module
by you. Two alternatives exist for teams already on them: --iac cdk writes a
TypeScript stack using the aws-cdk-lib L1 constructs for AWS::BedrockAgentCore::*
types, and --iac cli prints the AgentCore CLI (@aws/agentcore) commands without
writing anything. The Python starter toolkit is not offered: its CLI is no
longer supported.

Nothing is written without confirmation: run with --dry-run first, show the
write plan, then run again without it. Existing files are skipped unless
--force is passed. Nothing is planned or applied.

    scaffold.py <project> --component runtime|gateway|identity|memory
                [--iac terraform|cdk|cli] [--name NAME] [--out-dir DIR]
                [--protocol HTTP|MCP] [--dry-run] [--force] [--json]

Exit codes: 0 written or planned, 1 nothing to write, 2 bad arguments.
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

sys.dont_write_bytecode = True  # a read-only plugin install must stay clean: no __pycache__
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "lib"))

from agentcore_skills import DOCS_CHECKED, cli, data, tfgen  # noqa: E402
from agentcore_skills.project import load  # noqa: E402
from agentcore_skills.report import EXIT_OK, EXIT_USAGE  # noqa: E402
from agentcore_skills.templating import WritePlan  # noqa: E402

CDK_STACK = """// Generated by the agentcore plugin (agentcore-create). L1 constructs map 1:1
// to AWS::BedrockAgentCore::* CloudFormation types; property names follow the
// CloudFormation schema. Confirm them with `cdk synth` before deploying.
import * as cdk from "aws-cdk-lib";
import * as iam from "aws-cdk-lib/aws-iam";
import * as agentcore from "aws-cdk-lib/aws-bedrockagentcore";
import { Construct } from "constructs";

export interface {{CLASS}}Props extends cdk.StackProps {
  readonly discoveryUrl: string;      // https://cognito-idp.<region>.amazonaws.com/<pool>/.well-known/openid-configuration
  readonly allowedClients: string[];  // Cognito app client ids (client_id claim)
}

export class {{CLASS}} extends cdk.Stack {
  constructor(scope: Construct, id: string, props: {{CLASS}}Props) {
    super(scope, id, props);

    const role = new iam.Role(this, "ServiceRole", {
      assumedBy: new iam.ServicePrincipal("bedrock-agentcore.amazonaws.com", {
        conditions: { StringEquals: { "aws:SourceAccount": this.account } },
      }),
    });

{{BODY}}
  }
}
"""

CDK_BODIES = {
    "gateway": """    const gateway = new agentcore.CfnGateway(this, "Gateway", {
      name: "{{NAME}}",
      roleArn: role.roleArn,
      protocolType: "MCP",
      authorizerType: "CUSTOM_JWT",
      authorizerConfiguration: {
        customJwtAuthorizer: { discoveryUrl: props.discoveryUrl, allowedClients: props.allowedClients },
      },
      protocolConfiguration: { mcp: { supportedVersions: ["2025-11-25", "2026-07-28"] } },
    });
    new cdk.CfnOutput(this, "GatewayUrl", { value: gateway.attrGatewayUrl });""",
    "runtime": """    const runtime = new agentcore.CfnRuntime(this, "Runtime", {
      agentRuntimeName: "{{NAME_UNDERSCORE}}",
      roleArn: role.roleArn,
      agentRuntimeArtifact: { containerConfiguration: { containerUri: "<account>.dkr.ecr.<region>.amazonaws.com/{{NAME}}:<tag>" } },
      networkConfiguration: { networkMode: "PUBLIC" },
      protocolConfiguration: "{{PROTOCOL}}",
      authorizerConfiguration: {
        customJwtAuthorizer: { discoveryUrl: props.discoveryUrl, allowedClients: props.allowedClients },
      },
    });
    new cdk.CfnOutput(this, "RuntimeArn", { value: runtime.attrAgentRuntimeArn });""",
    "memory": """    const memory = new agentcore.CfnMemory(this, "Memory", {
      name: "{{NAME_UNDERSCORE}}",
      eventExpiryDuration: 30,
      memoryStrategies: [{ semanticMemoryStrategy: { name: "facts", namespaces: ["facts/{actorId}"] } }],
    });
    new cdk.CfnOutput(this, "MemoryId", { value: memory.attrMemoryId });""",
    "identity": """    const provider = new agentcore.CfnOAuth2CredentialProvider(this, "CognitoProvider", {
      name: "{{NAME}}-cognito",
      credentialProviderVendor: "CustomOauth2",
      oauth2ProviderConfigInput: {
        customOauth2ProviderConfig: {
          oauthDiscovery: { discoveryUrl: props.discoveryUrl },
          clientId: "<from a confidential Cognito client>",
          clientSecret: cdk.SecretValue.secretsManager("<secret-name>").unsafeUnwrap(),
        },
      },
    });
    void provider;""",
}

CLI_COMMANDS = {
    "runtime": ["agentcore create  # choose framework and model; writes agentcore.json", "agentcore dev     # local run",
                "agentcore deploy  # synthesises CDK (@aws/agentcore-cdk) and deploys", "agentcore invoke"],
    "gateway": ["agentcore add gateway --name {name} --authorizer-type CUSTOM_JWT \\\n"
                "  --discovery-url https://cognito-idp.<region>.amazonaws.com/<pool>/.well-known/openid-configuration \\\n"
                "  --allowed-audience <audience>", "agentcore deploy"],
    "identity": ["agentcore add credential --name {name}-cognito --type oauth \\\n"
                 "  --discovery-url <issuer>/.well-known/openid-configuration --client-id <id> --client-secret <secret>",
                 "agentcore deploy"],
    "memory": ["agentcore add memory  # follow the prompts for strategies", "agentcore deploy"],
}


def main(argv: list[str] | None = None) -> int:
    parser = cli.parser(__doc__)
    parser.add_argument("project", nargs="?", default=".")
    parser.add_argument("--component", required=True, choices=("runtime", "gateway", "identity", "memory"))
    parser.add_argument("--iac", choices=("terraform", "cdk", "cli"), default="terraform")
    parser.add_argument("--name", default=None)
    parser.add_argument("--out-dir", default=None)
    parser.add_argument("--protocol", choices=("HTTP", "MCP", "A2A", "AGUI"), default="HTTP")
    cli.add_writer(parser)
    args = parser.parse_args(argv)
    root = Path(args.project).expanduser()
    if not root.is_dir():
        print(f"error: {root} is not a directory", file=sys.stderr)
        return EXIT_USAGE
    name = args.name or tfgen.aws_name(root.resolve().name)
    project = load(root)
    region = project.primary_region()
    notes = []
    if region and data.service_available(args.component if args.component != "identity" else "identity", region) is False:
        notes.append(f"{args.component} is not available in {region}; see the regions table")

    if args.iac == "cli":
        commands = [c.format(name=name) for c in CLI_COMMANDS[args.component]]
        payload = {"component": args.component, "iac": "cli", "commands": commands,
                   "note": "AgentCore CLI (npm install -g @aws/agentcore); it owns its own CDK app and agentcore.json"}
        if args.format == "json":
            import json
            print(json.dumps(payload, indent=2))
        else:
            print("# AgentCore CLI commands (not run)\n\n```bash\n" + "\n".join(commands) + "\n```\n\n" + payload["note"])
        return EXIT_OK

    plan = WritePlan()
    if args.iac == "cdk":
        from agentcore_skills.templating import render
        class_name = "".join(part.capitalize() for part in name.replace("_", "-").split("-")) + "AgentCoreStack"
        body = render(CDK_BODIES[args.component], {"NAME": name, "NAME_UNDERSCORE": name.replace("-", "_"),
                                                     "PROTOCOL": args.protocol}, strict=False)
        stack = render(CDK_STACK, {"CLASS": class_name, "BODY": body}, strict=False)
        target = Path(args.out_dir) if args.out_dir else root / "cdk" / "lib" / f"{name}-{args.component}-stack.ts"
        if not target.is_absolute():
            target = root / target
        plan.add(target, stack, force=args.force)
        notes.append("register the stack in your CDK app (bin/*.ts) and run `cdk synth` to validate property names")
        return cli.finish_plan(plan, fmt=args.format, dry_run=args.dry_run, notes=notes)

    checked = DOCS_CHECKED or date.today().isoformat()
    if args.component == "runtime":
        files = tfgen.runtime_module(name=name, protocol=args.protocol, checked=checked, jwt=True)
        default_dir = "agentcore-runtime"
        notes.append("build the image with `docker buildx build --platform linux/arm64`; /agentcore:agentcore-runtime "
                     "checks the container contract")
    elif args.component == "gateway":
        files = tfgen.gateway_module(name=name, upstream="lambda", checked=checked)
        default_dir = "agentcore-gateway"
        notes.append("for a gateway in front of an existing Lambda, HTTP API or MCP server use /agentcore:agentcore-gateway")
    elif args.component == "identity":
        pool = project.cognito_pools()[0].address if project.cognito_pools() else None
        files = tfgen.identity_module(recipe="cognito-m2m-outbound", name=name, checked=checked, pool_ref=None,
                                      resource_server=None, scopes=[])
        default_dir = "agentcore-identity"
        if pool:
            notes.append(f"pass user_pool_id = {pool}.id from the root module")
    else:
        files = tfgen.memory_module(name=name, checked=checked, expiry_days=30, strategies=["SEMANTIC"], kms=True)
        default_dir = "agentcore-memory"
    out = cli.module_dir(root, args.out_dir, default_dir)
    for rel, content in files.items():
        plan.add(out / rel, content, force=args.force)
    notes.append(f"wire it from your root module: module \"{default_dir.replace('-', '_')}\" {{ source = \"<path to {out.name}>\" ... }}")
    notes.append("then run /agentcore:agentcore-review and /agentcore:agentcore-deploy for the plan")
    return cli.finish_plan(plan, fmt=args.format, dry_run=args.dry_run, notes=notes,
                           extra={"component": args.component, "iac": "terraform", "module_dir": str(out)})


if __name__ == "__main__":
    raise SystemExit(main())
