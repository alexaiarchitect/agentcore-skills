#!/usr/bin/env python3
"""Write a Dockerfile that meets the AgentCore Runtime container contract.

What is generated, and why each line is there:

* `FROM --platform=linux/arm64` — Runtime runs ARM64 images only;
* a non-root user and no credential of any kind: configuration arrives as
  Runtime environment variables, secrets through AgentCore Identity;
* the contract port: 8080 for HTTP (/invocations, /ping), 8000 for MCP
  (/mcp, stateless Streamable HTTP);
* `opentelemetry-instrument` in front of the Python entry point (ADOT), so
  spans reach CloudWatch GenAI observability without code changes;
* a .dockerignore that keeps .env, .git and local virtualenvs out.

    gen_dockerfile.py <project> [--protocol HTTP|MCP] [--language python|node]
                      [--entry agent.py] [--python 3.12] [--dry-run] [--force] [--json]

Exit codes: 0 written (or planned under --dry-run), 1 nothing to write,
2 bad arguments.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.dont_write_bytecode = True  # a read-only plugin install must stay clean: no __pycache__
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "lib"))

from agentcore_skills import cli  # noqa: E402
from agentcore_skills.report import EXIT_USAGE  # noqa: E402
from agentcore_skills.templating import WritePlan, render  # noqa: E402

PYTHON = """# AgentCore Runtime image ({{PROTOCOL}} protocol). Generated by the agentcore plugin.
# Runtime requires linux/arm64 and calls the container on 0.0.0.0:{{PORT}}.
FROM --platform=linux/arm64 python:{{PYTHON}}-slim

RUN useradd --create-home --uid 10001 agent
WORKDIR /app

COPY requirements.txt ./
# aws-opentelemetry-distro (ADOT) must be in requirements.txt for the CMD below.
RUN pip install --no-cache-dir -r requirements.txt

COPY {{ENTRY}} ./

ENV PYTHONUNBUFFERED=1 \\
    AGENT_OBSERVABILITY_ENABLED=true

USER agent
EXPOSE {{PORT}}

# {{CONTRACT}}
CMD ["opentelemetry-instrument", "python", "{{ENTRY}}"]
"""

NODE = """# AgentCore Runtime image ({{PROTOCOL}} protocol). Generated by the agentcore plugin.
# Runtime requires linux/arm64 and calls the container on 0.0.0.0:{{PORT}}.
FROM --platform=linux/arm64 node:24-slim

WORKDIR /app
COPY package*.json ./
RUN npm ci --omit=dev
COPY dist ./dist

ENV NODE_ENV=production
USER node
EXPOSE {{PORT}}

# {{CONTRACT}}
CMD ["node", "{{ENTRY}}"]
"""

DOCKERIGNORE = """.env
.env.*
!.env.example
.git
.venv
venv
node_modules
__pycache__
*.pyc
.terraform
"""

CONTRACTS = {
    "HTTP": "POST /invocations (JSON or SSE) and GET /ping -> {\"status\": \"Healthy\"|\"HealthyBusy\"}",
    "MCP": "POST /mcp, Streamable HTTP, stateless; accept the platform's Mcp-Session-Id header",
}


def main(argv: list[str] | None = None) -> int:
    parser = cli.parser(__doc__)
    parser.add_argument("project", nargs="?", default=".")
    parser.add_argument("--protocol", choices=("HTTP", "MCP"), default="HTTP")
    parser.add_argument("--language", choices=("python", "node"), default="python")
    parser.add_argument("--entry", default=None)
    parser.add_argument("--python", default="3.12", choices=("3.10", "3.11", "3.12", "3.13"))
    cli.add_writer(parser)
    args = parser.parse_args(argv)
    root = Path(args.project).expanduser()
    if not root.is_dir():
        print(f"error: {root} is not a directory", file=sys.stderr)
        return EXIT_USAGE
    entry = args.entry or ("agent.py" if args.language == "python" else "dist/server.js")
    port = "8080" if args.protocol == "HTTP" else "8000"
    template = PYTHON if args.language == "python" else NODE
    content = render(template, {"PROTOCOL": args.protocol, "PORT": port, "PYTHON": args.python, "ENTRY": entry,
                                "CONTRACT": CONTRACTS[args.protocol]})
    plan = WritePlan()
    plan.add(root / "Dockerfile", content, force=args.force)
    plan.add(root / ".dockerignore", DOCKERIGNORE, force=args.force)
    notes = ["build: docker buildx build --platform linux/arm64 -t <repo>:<tag> --push .",
             "then: python3 scripts/runtime_check.py <project> to confirm the contract"]
    if args.language == "python" and not (root / "requirements.txt").is_file():
        notes.insert(0, "requirements.txt is missing: add bedrock-agentcore and aws-opentelemetry-distro")
    return cli.finish_plan(plan, fmt=args.format, dry_run=args.dry_run, notes=notes)


if __name__ == "__main__":
    raise SystemExit(main())
