#!/usr/bin/env python3
"""Write a plan-only CI workflow for AgentCore infrastructure, with policy gates.

The workflow never applies. On a pull request that touches infrastructure it
runs terraform fmt -check, validate, the static review (ACR0xx), a saved
plan, `terraform show -json`, and the plan policy (CI0xx: no deletion of
memory, gateways, credential providers or user pools; no * on *; no
unauthenticated gateway), then uploads the plan JSON for review. Apply stays a
separate, human-approved step (agentcore-deploy).

So the job needs nothing from this plugin at run time, the generator vendors
the plugin's stdlib-only library into ci/agentcore/ with a small entry point
(`python3 ci/agentcore/run.py review|policy ...`). Action references are
reused from the project's existing workflows when they are SHA-pinned; the
fallbacks are the SHA pins the first user's repository carried on 2026-10-05,
labelled with their tags — re-verify them against your own policy.

    gen_ci.py <project> [--tf-root DIR] [--role-var AWS_PLAN_ROLE_ARN] [--region R]
              [--terraform 1.14.2] [--dry-run] [--force] [--json]

Exit codes: 0 written (or planned), 1 nothing to write, 2 bad arguments.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # a read-only plugin install must stay clean: no __pycache__
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "lib"))

from agentcore_skills import cli, hcl  # noqa: E402
from agentcore_skills.project import load  # noqa: E402
from agentcore_skills.report import EXIT_USAGE, GapReport  # noqa: E402
from agentcore_skills.templating import WritePlan, render  # noqa: E402

LIB = Path(__file__).resolve().parents[3] / "lib" / "agentcore_skills"
DEFAULT_PINS = {
    "actions/checkout": "actions/checkout@11bd71901bbe5b1630ceea73d27597364c9af683 # v4.2.2",
    "hashicorp/setup-terraform": "hashicorp/setup-terraform@5e8dbf3c6d9deaf4193ca7a8fb23f2ac83bb6c85 # v4.0.0",
    "aws-actions/configure-aws-credentials": "aws-actions/configure-aws-credentials@acca2b1b2070338fb9fd1ca27ecee81d687e58e5 # v6.1.2",
    "actions/upload-artifact": "actions/upload-artifact@v4 # pin to a full commit SHA",
}

WORKFLOW = """# Generated by the agentcore plugin (agentcore-ci). Plan only: nothing here applies.
name: AgentCore plan

on:
  pull_request:
    paths:
      - "{{TF_PATH}}/**"
      - ".github/workflows/agentcore-plan.yml"
      - "ci/agentcore/**"
  workflow_dispatch:

permissions:
  contents: read
  id-token: write

concurrency:
  group: agentcore-plan-${{ github.ref }}
  cancel-in-progress: true

env:
  TF_IN_AUTOMATION: "true"
  TF_INPUT: "false"

jobs:
  static:
    runs-on: ubuntu-24.04
    timeout-minutes: 15
    steps:
      - uses: {{CHECKOUT}}
      - name: Static AgentCore review (ACR0xx, no AWS calls)
        run: python3 ci/agentcore/run.py review . --fail-on error
      - uses: {{SETUP_TERRAFORM}}
        with:
          terraform_version: {{TERRAFORM}}
          terraform_wrapper: false
      - name: Format
        run: terraform fmt -check -recursive {{TF_PATH}}

  plan:
    needs: static
    if: github.event_name == 'workflow_dispatch' || github.event.pull_request.head.repo.full_name == github.repository
    runs-on: ubuntu-24.04
    timeout-minutes: 30
    steps:
      - uses: {{CHECKOUT}}
      - uses: {{SETUP_TERRAFORM}}
        with:
          terraform_version: {{TERRAFORM}}
          terraform_wrapper: false
      - uses: {{CONFIGURE_AWS}}
        with:
          role-to-assume: ${{ vars.{{ROLE_VAR}} }}
          aws-region: {{REGION}}
          role-session-name: agentcore-plan-${{ github.run_id }}
{{TERRAGRUNT_INSTALL}}      - name: Plan (read-only role)
        working-directory: {{ROOT}}
        run: |
          {{TOOL}} init -input=false
          {{TOOL}} validate
          {{TOOL}} plan -input=false -lock-timeout=5m -out=agentcore.tfplan
          {{TOOL}} show -json agentcore.tfplan > agentcore.plan.json
      - name: Plan policy (CI0xx)
        run: python3 ci/agentcore/run.py policy {{ROOT}}/agentcore.plan.json
      - uses: {{UPLOAD}}
        if: always()
        with:
          name: agentcore-plan
          path: {{ROOT}}/agentcore.plan.json
          retention-days: 7
"""

TERRAGRUNT_STEP = """      - name: Install Terragrunt
        run: |
          # Pin the version and checksum your repository already uses.
          curl --fail --location --silent --show-error --output terragrunt \\
            https://github.com/gruntwork-io/terragrunt/releases/download/${{ vars.TERRAGRUNT_VERSION }}/terragrunt_linux_amd64
          echo "${{ vars.TERRAGRUNT_SHA256 }}  terragrunt" | sha256sum --check
          sudo install -m 0755 terragrunt /usr/local/bin/terragrunt
"""

RUNNER = '''#!/usr/bin/env python3
"""Vendored by the agentcore plugin's gen_ci.py: CI entry point, stdlib only.

    python3 ci/agentcore/run.py review <project> [--fail-on error|warn]
    python3 ci/agentcore/run.py policy <plan.json> [--allow-replace ADDRESS ...]
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from agentcore_skills import plan_policy, rules  # noqa: E402
from agentcore_skills.project import load  # noqa: E402
from agentcore_skills.report import GapReport  # noqa: E402


def review(argv):
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("project")
    parser.add_argument("--fail-on", choices=("error", "warn"), default="error")
    args = parser.parse_args(argv)
    project = load(args.project)
    report = GapReport(subject=args.project, skill="agentcore-review")
    rules.run_all(project, report)
    print(report.to_md())
    if report.count("error") or (args.fail_on == "warn" and report.count("warn")):
        return 1
    return 0


if __name__ == "__main__":
    command, rest = (sys.argv[1], sys.argv[2:]) if len(sys.argv) > 1 else ("", [])
    if command == "review":
        raise SystemExit(review(rest))
    if command == "policy":
        raise SystemExit(plan_policy.main(rest))
    print("usage: run.py review|policy ...", file=sys.stderr)
    raise SystemExit(2)
'''


def existing_pins(root: Path) -> dict[str, str]:
    pins: dict[str, str] = {}
    workflows = root / ".github" / "workflows"
    if not workflows.is_dir():
        return pins
    for path in sorted(workflows.glob("*.y*ml")):
        for match in re.finditer(r"uses:\s*([\w.\-]+/[\w.\-]+)@([0-9a-f]{40})(\s*#\s*\S+)?", hcl.read_text(path)):
            pins.setdefault(match.group(1), f"{match.group(1)}@{match.group(2)}{(' ' + match.group(3).strip()) if match.group(3) else ''}")
    return pins


def main(argv: list[str] | None = None) -> int:
    parser = cli.parser(__doc__)
    parser.add_argument("project", nargs="?", default=".")
    parser.add_argument("--tf-root", help="root module or Terragrunt stack to plan")
    parser.add_argument("--role-var", default="AWS_PLAN_ROLE_ARN", help="GitHub variable holding a read-only plan role")
    parser.add_argument("--region", default=None)
    parser.add_argument("--terraform", default=None)
    cli.add_writer(parser)
    args = parser.parse_args(argv)
    root = Path(args.project).expanduser()
    if not root.is_dir():
        print(f"error: {root} is not a directory", file=sys.stderr)
        return EXIT_USAGE
    project = load(root)
    report = GapReport(subject=str(project.root), skill="agentcore-ci")
    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "agentcore-deploy" / "scripts"))
    from deploy_plan import find_roots  # noqa: E402

    roots = find_roots(project)
    tf_root = Path(args.tf_root) if args.tf_root else (roots[0] if roots else root)
    if not tf_root.is_absolute():
        tf_root = root / tf_root
    rel_root = project.rel(tf_root)
    terragrunt = (tf_root / "terragrunt.hcl").is_file()
    tf_path = rel_root.split("/")[0] if "/" in rel_root else rel_root
    required = project.tf.required_version() or ""
    terraform = args.terraform or (re.sub(r"[^0-9.]", "", required) if re.fullmatch(r"=?\s*\d+\.\d+\.\d+", required.strip()) else "1.14.2")
    pins = {**DEFAULT_PINS, **existing_pins(root)}
    if not existing_pins(root):
        report.add("CI010", "info", "pins", "no SHA-pinned actions found in this repository; the workflow uses the "
                   "plugin's fallback pins", fix="replace them with the pins your security policy approves.")
    if any(b.type.startswith("aws_iam_") for b in project.tf.blocks if b.kind == "resource"):
        report.add("CI011", "info", "role", f"the plan job assumes ${{{{ vars.{args.role_var} }}}}: give it read-only "
                   "permissions (plan needs Describe/Get/List and state access), never the deploy role")
    workflow = render(WORKFLOW, {
        "TF_PATH": tf_path or ".", "ROOT": rel_root or ".", "TERRAFORM": terraform,
        "CHECKOUT": pins["actions/checkout"], "SETUP_TERRAFORM": pins["hashicorp/setup-terraform"],
        "CONFIGURE_AWS": pins["aws-actions/configure-aws-credentials"],
        "UPLOAD": pins.get("actions/upload-artifact", DEFAULT_PINS["actions/upload-artifact"]),
        "ROLE_VAR": args.role_var, "REGION": args.region or project.primary_region() or "us-east-1",
        "TOOL": "terragrunt" if terragrunt else "terraform",
        "TERRAGRUNT_INSTALL": TERRAGRUNT_STEP if terragrunt else "",
    }, strict=False)
    plan = WritePlan()
    plan.add(root / ".github" / "workflows" / "agentcore-plan.yml", workflow, force=args.force)
    plan.add(root / "ci" / "agentcore" / "run.py", RUNNER, force=args.force)
    for module in sorted(LIB.glob("*.py")):
        plan.add(root / "ci" / "agentcore" / "agentcore_skills" / module.name, module.read_text(encoding="utf-8"),
                 force=args.force, reason="vendored, stdlib only")
    for data_file in sorted((LIB / "data").glob("*.json")):
        plan.add(root / "ci" / "agentcore" / "agentcore_skills" / "data" / data_file.name,
                 data_file.read_text(encoding="utf-8"), force=args.force)
    report.discovered = {"tf_root": rel_root, "terragrunt": terragrunt, "terraform": terraform,
                         "role_var": args.role_var, "pins_from_repo": sorted(existing_pins(root))}
    notes = [f"create the GitHub variable {args.role_var} with a read-only role trusted by GitHub OIDC",
             "the plan job never applies; apply through agentcore-deploy after review"]
    return cli.finish_plan(plan, fmt=args.format, dry_run=args.dry_run, report=report, notes=notes)


if __name__ == "__main__":
    raise SystemExit(main())
