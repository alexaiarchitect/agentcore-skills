def identity_module(*, recipe: str, name: str, checked: str, pool_ref: str | None,
                    resource_server: str | None, scopes: list[str],
                    existing_client: bool = False) -> dict[str, str]:
    """Recipes: cognito-inbound, cognito-m2m-outbound, api-key-outbound, workload-identity.

    `existing_client` (cognito-m2m-outbound): take the client id and secret of
    a Cognito app client the project already has as inputs instead of creating
    a dedicated `gateway_outbound` client.
    """
    pool_id = f"{pool_ref}.id" if pool_ref else "var.user_pool_id"
    region = "${data.aws_region.current.region}"
    main = header("agentcore-identity", checked) + 'data "aws_region" "current" {}\n'
    outputs = ""
    variables = """variable "tags" {
  type    = map(string)
  default = {}
}
"""
    if not pool_ref:
        variables += """
variable "user_pool_id" {
  type = string
}
"""
    if recipe == "cognito-inbound":
        main += f"""
# Inbound: nothing to create in AgentCore. A gateway or runtime trusts the
# pool through its custom_jwt_authorizer; these locals are what to pass in.
locals {{
  discovery_url = "{cognito_discovery_url(region, '${' + pool_id + '}')}"
}}
"""
        outputs += """output "discovery_url" {
  value = local.discovery_url
}
"""
    elif recipe == "cognito-m2m-outbound":
        scope_list = hcl_list([f"{resource_server}/{s}" for s in scopes]) if resource_server else "var.oauth_scopes"
        if existing_client:
            client_id_expr, client_secret_expr = "var.client_id", "var.client_secret"
            main += """
# Outbound: an existing confidential Cognito client (client credentials) the
# gateway presents to your upstream. It is one principal for every caller: if
# the upstream derives ownership from the token subject, read
# identity-propagation.md first. Its scopes are whatever that client allows.
"""
        else:
            client_id_expr = "aws_cognito_user_pool_client.gateway_outbound.id"
            client_secret_expr = "aws_cognito_user_pool_client.gateway_outbound.client_secret"
            main += f"""
# Outbound: a confidential Cognito client the gateway uses (client credentials)
# when it calls your upstream. It is one principal for every caller: if the
# upstream derives ownership from the token subject, read identity-propagation.md first.
resource "aws_cognito_user_pool_client" "gateway_outbound" {{
  name                                 = "${{var.name}}-gateway-outbound"
  user_pool_id                         = {pool_id}
  generate_secret                      = true
  allowed_oauth_flows                  = ["client_credentials"]
  allowed_oauth_flows_user_pool_client = true
  allowed_oauth_scopes                 = {scope_list}
  supported_identity_providers         = ["COGNITO"]
  access_token_validity                = 60
  token_validity_units {{
    access_token = "minutes"
  }}
}}
"""
        main += f"""
# The token vault holds the client secret. The write-only arguments keep it out
# of *this resource's* state (bump client_credentials_wo_version to rotate);
# the Cognito app client resource that generates the secret still stores
# `client_secret` in Terraform state, so the state backend must be protected
# (encrypted, access-controlled) either way.
resource "aws_bedrockagentcore_oauth2_credential_provider" "cognito" {{
  name                       = "${{var.name}}-cognito"
  credential_provider_vendor = "CustomOauth2"

  oauth2_provider_config {{
    custom_oauth2_provider_config {{
      client_id_wo                  = {client_id_expr}
      client_secret_wo              = {client_secret_expr}
      client_credentials_wo_version = var.client_credentials_version

      oauth_discovery {{
        discovery_url = "{cognito_discovery_url(region, '${' + pool_id + '}')}"
      }}
    }}
  }}
}}
"""
        variables += """
variable "name" {
  type = string
}

variable "client_credentials_version" {
  type    = number
  default = 1
}
"""
        if existing_client:
            variables += """
variable "client_id" {
  description = "App client id of the existing confidential Cognito client (client_credentials flow)"
  type        = string
}

variable "client_secret" {
  description = "Its client secret; pass the client resource's client_secret attribute"
  type        = string
  sensitive   = true
}
"""
        elif not resource_server:
            variables += """
variable "oauth_scopes" {
  type = list(string)
}
"""
        outputs += f"""output "oauth_provider_arn" {{
  value = aws_bedrockagentcore_oauth2_credential_provider.cognito.credential_provider_arn
}}

output "credential_secret_arn" {{
  value = aws_bedrockagentcore_oauth2_credential_provider.cognito.client_secret_arn
}}

output "outbound_client_id" {{
  value = {client_id_expr}
}}
"""
    elif recipe == "api-key-outbound":
        main += """
# An API key for an upstream that takes one. The write-only argument keeps the
# key out of state; supply it from a sensitive variable at apply time.
resource "aws_bedrockagentcore_api_key_credential_provider" "upstream" {
  name               = "${var.name}-api-key"
  api_key_wo         = var.api_key
  api_key_wo_version = var.api_key_version
}
"""
        variables += """
variable "name" {
  type = string
}

variable "api_key" {
  type      = string
  sensitive = true
  ephemeral = true
}

variable "api_key_version" {
  type    = number
  default = 1
}
"""
        outputs += """output "api_key_provider_arn" {
  value = aws_bedrockagentcore_api_key_credential_provider.upstream.credential_provider_arn
}

output "credential_secret_arn" {
  value = aws_bedrockagentcore_api_key_credential_provider.upstream.api_key_secret_arn
}
"""
    elif recipe == "workload-identity":
        main += """
# A standalone workload identity for an agent that is not hosted on Runtime
# (Runtime and Gateway create their own). Return URLs bound here are the only
# ones a three-legged OAuth flow may redirect to.
resource "aws_bedrockagentcore_workload_identity" "agent" {
  name                                = var.name
  allowed_resource_oauth2_return_urls = var.return_urls
}
"""
        variables += """
variable "name" {
  type = string
}

variable "return_urls" {
  type    = list(string)
  default = []
}
"""
        outputs += """output "workload_identity_arn" {
  value = aws_bedrockagentcore_workload_identity.agent.workload_identity_arn
}
"""
    else:
        raise ValueError(f"unknown recipe {recipe}")
    if "variable \"name\"" not in variables:
        variables += f"""
variable "name" {{
  type    = string
  default = {json.dumps(aws_name(name))}
}}
"""
    return {"main.tf": main, "variables.tf": variables, "outputs.tf": outputs, "versions.tf": versions_tf()}


