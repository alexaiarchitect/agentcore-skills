STRATEGY_TYPES = ("SEMANTIC", "SUMMARIZATION", "USER_PREFERENCE", "EPISODIC")


def memory_module(*, name: str, checked: str, expiry_days: int, strategies: list[str], kms: bool) -> dict[str, str]:
    kms_block = """
resource "aws_kms_key" "memory" {
  description         = "AgentCore Memory for ${var.name}"
  enable_key_rotation = true
  tags                = var.tags
}
""" if kms else ""
    kms_arg = "\n  encryption_key_arn = aws_kms_key.memory.arn" if kms else ""
    strategy_blocks = []
    for kind in strategies:
        namespace = {"SEMANTIC": "facts/{actorId}", "SUMMARIZATION": "summaries/{actorId}/{sessionId}",
                     "USER_PREFERENCE": "preferences/{actorId}", "EPISODIC": "episodes/{actorId}"}[kind]
        strategy_blocks.append(f"""
resource "aws_bedrockagentcore_memory_strategy" "{kind.lower()}" {{
  name                = "{kind.lower()}"
  memory_id           = aws_bedrockagentcore_memory.this.id
  type                = "{kind}"
  # Exactly one namespace template; records are scoped by actor so one user's
  # memories are never retrieved for another.
  namespace_templates = ["{namespace}"]
}}
""")
    main = header("agentcore-memory", checked) + kms_block + f"""
# Short-term memory (raw events) expires after event_expiry_duration days
# (7..365). Long-term records are extracted from those events by the strategies.
resource "aws_bedrockagentcore_memory" "this" {{
  name                  = replace(var.name, "-", "_")
  description           = var.description
  event_expiry_duration = var.event_expiry_days{kms_arg}
  tags                  = var.tags
}}
""" + "".join(strategy_blocks)
    variables = f"""variable "name" {{
  type    = string
  default = {json.dumps(aws_name(name))}
}}

variable "description" {{
  type    = string
  default = "Agent memory"
}}

variable "event_expiry_days" {{
  type    = number
  default = {expiry_days}
  validation {{
    condition     = var.event_expiry_days >= 7 && var.event_expiry_days <= 365
    error_message = "AgentCore Memory keeps events for 7 to 365 days."
  }}
}}

variable "tags" {{
  type    = map(string)
  default = {{}}
}}
"""
    outputs = """output "memory_id" {
  value = aws_bedrockagentcore_memory.this.id
}

output "memory_arn" {
  value = aws_bedrockagentcore_memory.this.arn
}
"""
    return {"main.tf": main, "variables.tf": variables, "outputs.tf": outputs, "versions.tf": versions_tf()}


