def test_ci_workflow_is_plan_only_and_vendors_the_library(run_script, tmp_project):
    root = tmp_project("vault_like")
    result = run_script(GEN_CI, root, "--json")
    assert result.returncode == EXIT_OK
    workflow = (root / ".github" / "workflows" / "agentcore-plan.yml").read_text()
    assert "plan -input=false" in workflow and "terragrunt" in workflow
    assert " apply" not in workflow.replace("# Generated by the agentcore plugin (agentcore-ci). Plan only: nothing here applies.", "")
    assert "id-token: write" in workflow and "@11bd71901bbe5b1630ceea73d27597364c9af683" in workflow
    yaml_free_check.assert_balanced_yaml(workflow)
    assert (root / "ci" / "agentcore" / "agentcore_skills" / "plan_policy.py").is_file()
    assert (root / "ci" / "agentcore" / "agentcore_skills" / "data" / "regions.json").is_file()


def test_vendored_runner_works_without_the_plugin(run_script, tmp_project, fixtures, tmp_path):
    import subprocess
    import sys

    root = tmp_project("gateway_good")
    run_script(GEN_CI, root)
    isolated = tmp_path / "isolated"
    shutil.copytree(root, isolated)
    review = subprocess.run([sys.executable, "ci/agentcore/run.py", "review", "."], cwd=isolated,
                            capture_output=True, text=True, env={"PATH": "/usr/bin:/bin"})
    assert review.returncode == 0, review.stdout + review.stderr
    policy = subprocess.run([sys.executable, "ci/agentcore/run.py", "policy", str(fixtures / "plans" / "plan_bad.json")],
                            cwd=isolated, capture_output=True, text=True, env={"PATH": "/usr/bin:/bin"})
    assert policy.returncode == 1 and "CI001" in policy.stdout


def test_ci_reuses_the_repositorys_pins(run_script, tmp_project):
    root = tmp_project("vault_like")
    workflows = root / ".github" / "workflows"
    workflows.mkdir(parents=True)
    (workflows / "ci.yml").write_text("steps:\n  - uses: actions/checkout@" + "a" * 40 + " # v9.9.9\n")
    run_script(GEN_CI, root)
    assert "actions/checkout@" + "a" * 40 in (workflows / "agentcore-plan.yml").read_text()


def test_policy_check_exit_codes(run_script, fixtures):
    assert run_script(POLICY, fixtures / "plans" / "plan_ok.json").returncode == EXIT_OK
    bad = run_script(POLICY, fixtures / "plans" / "plan_bad.json", "--json")
    assert bad.returncode == EXIT_FINDINGS and "CI001" in bad.ids()
    allowed = run_script(POLICY, fixtures / "plans" / "plan_bad.json", "--allow-replace",
                         "module.memory.aws_bedrockagentcore_memory.this", "--json").json()
    assert sum(1 for f in allowed["findings"] if f["id"] == "CI001") == 1
    assert run_script(POLICY, fixtures / "plans" / "not_a_plan.json").returncode == EXIT_USAGE


