def test_deploy_picks_the_application_root_and_terragrunt(run_script, project):
    doc = run_script(DEPLOY, project("vault_like"), "--json").json()
    found = doc["discovered"]
    assert found["root_module"] == "infrastructure/live/production" and found["terragrunt"] is True
    assert found["commands"][0] == "terragrunt init -input=false"
    assert any("show -json" in c for c in found["commands"])
    assert "DPL005" in {f["id"] for f in doc["findings"]}


def test_deploy_commands_apply_only_a_saved_plan(run_script, project):
    doc = run_script(DEPLOY, project("gateway_good"), "--json").json()
    commands = doc["discovered"]["commands"]
    assert commands[-1].splitlines()[-1].endswith("apply agentcore.tfplan")
    assert "auto-approve" not in " ".join(commands)
    assert doc["options"][0]["cost"] == "aws"
    assert {"core", "attachments", "telemetry"} <= set(doc["discovered"]["stages"])


