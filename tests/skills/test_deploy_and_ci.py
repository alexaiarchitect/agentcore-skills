def test_deploy_executes_nothing(run_script, tmp_project, monkeypatch, tmp_path):
    """With terraform, terragrunt and aws replaced by tripwires on PATH, the
    script still succeeds and no tripwire fires."""
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    marker = tmp_path / "fired"
    for tool in ("terraform", "terragrunt", "aws"):
        path = bin_dir / tool
        path.write_text(f"#!/bin/sh\necho {tool} >> {marker}\n")
        path.chmod(0o755)
    root = tmp_project("vault_like")
    result = run_script(DEPLOY, root, env={"PATH": f"{bin_dir}:/usr/bin:/bin"})
    assert result.returncode == EXIT_OK
    assert not marker.exists()


